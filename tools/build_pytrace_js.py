"""Copy tools/pytrace.py into assets/js/pytrace-src.js so the in-browser
"Edit and run" box (Kit.pyRunner, running Pyodide) uses the same tracer as the
pre-built traces. Run from the repo root after editing pytrace.py:
    python3 tools/build_pytrace_js.py
"""
import json, os
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = open(os.path.join(root, "tools", "pytrace.py")).read()
dst = os.path.join(root, "assets", "js", "pytrace-src.js")
with open(dst, "w") as f:
    f.write("/* generated by tools/build_pytrace_js.py from tools/pytrace.py - do not edit */\n")
    f.write("window.PYTRACE_SRC = " + json.dumps(src) + ";\n")
print("wrote", dst)
