#!/usr/bin/env python3
"""Build assets/js/search-index.js: every explainer page with its title and subject.

Run from the repo root after adding or renaming a page:

    python3 tools/build_search_index.py

The home page loads the generated file and searches it in the browser.
Pages are found by folder; each entry takes the page's <title>, meta description
and its h1 to h3 headings (as search words).
"""
import html
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "assets" / "js" / "search-index.js"

# folder -> (subject shown in results, track label or None)
FOLDERS = [
    ("system-design/hld", "System Design", "HLD"),
    ("system-design/lld", "System Design", "LLD"),
    ("system-design", "System Design", None),
    ("aws-cloud-practitioner", "AWS", None),
    ("python-fundamentals", "Python", None),
    ("angular", "Angular", None),
]

TITLE = re.compile(r"<title>(.*?)</title>", re.S | re.I)
LEDE = re.compile(r'<ul class="lede">(.*?)</ul>', re.S | re.I)
HEADS = re.compile(r"<h[1-3][^>]*>(.*?)</h[1-3]>", re.S | re.I)
TAGS = re.compile(r"<[^>]+>")
DESC = re.compile(r'<meta\s+name="description"\s+content="([^"]*)"', re.I)


def clean(fragment):
    return re.sub(r"\s+", " ", html.unescape(TAGS.sub(" ", fragment))).strip()


def entries():
    pages, seen = [], set()
    for folder, subject, track in FOLDERS:
        for page in sorted((ROOT / folder).glob("*.html")):
            rel = page.relative_to(ROOT).as_posix()
            if rel not in seen:
                seen.add(rel)
                pages.append((page, rel, subject, track))
    texts = {rel: page.read_text(encoding="utf-8", errors="ignore") for page, rel, _, _ in pages}
    # headings that repeat on many pages ("Test yourself") say nothing about a page
    count = {}
    for text in texts.values():
        for h in {clean(re.sub(r"^\d+", "", x)) for x in HEADS.findall(text)}:
            count[h] = count.get(h, 0) + 1
    for page, rel, subject, track in pages:
        text = texts[rel]
        m = TITLE.search(text)
        if not m:
            continue
        title = re.sub(r"\s*[·|]\s*See How It Works$", "", html.unescape(m.group(1)).strip())
        d = DESC.search(text)
        words = []
        lede = LEDE.search(text)
        if lede:
            words.append(clean(lede.group(1)))
        for h in HEADS.findall(text):
            h = clean(re.sub(r"^\d+", "", h))
            if h and h != title and count.get(h, 0) < 5 and "${" not in h and h not in words:
                words.append(h)
        kind = "Roadmap" if page.name in ("index.html", "map.html") else (track or "")
        yield {
            "t": title,
            "s": subject,
            "k": kind,
            "h": rel,
            "d": html.unescape(d.group(1)).strip() if d else "",
            "w": " ".join(words)[:500],
        }


def main():
    items = list(entries())
    body = json.dumps(items, ensure_ascii=False, indent=0)
    OUT.write_text(
        "/* Generated by tools/build_search_index.py. Do not edit by hand. */\n"
        f"window.SEARCH_INDEX = {body};\n",
        encoding="utf-8",
    )
    print(f"wrote {OUT.relative_to(ROOT)} with {len(items)} pages")


if __name__ == "__main__":
    main()
